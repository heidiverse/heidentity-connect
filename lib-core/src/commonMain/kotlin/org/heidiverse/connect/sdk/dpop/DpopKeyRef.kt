package org.heidiverse.connect.sdk.dpop

import kotlinx.serialization.Serializable

/**
 * An opaque reference to a DPoP key living in the platform's secure key storage (Android Keystore / iOS keychain with
 * Secure Enclave). This is what gets persisted next to the tokens — it never contains key material, and the private key
 * cannot be extracted from the secure element at all.
 */
@Serializable
data class DpopKeyRef(
	/** The Android Keystore alias / the iOS `kSecAttrApplicationTag` identifying the key pair. */
	val alias: String,

	val algorithm: DpopAlgorithm,

	/**
	 * Whether the key is backed by a secure element. False only when [DpopConfig.allowSoftwareKeyFallback] was enabled
	 * and no secure element was available.
	 */
	val isHardwareBacked: Boolean,
) {
	companion object {
		/**
		 * Prefix of every alias generated by this SDK. Used to scope key enumeration so that pruning orphaned keys can
		 * never touch keys belonging to the host app.
		 */
		const val ALIAS_PREFIX = "org.heidiverse.connect.sdk.dpop."
	}
}
